"""Generate the twelve pencil tile PNGs and the packed C ink tiles (stdlib only).

scripts/generate-grain.py draws the tiles procedurally; no other assets are read.
--check verifies the committed files without writing. --swift additionally
compares the PNG bytes with the Grain directory of an rmrender-swift checkout.
"""
import argparse
from pathlib import Path
import runpy

ROOT=Path(__file__).resolve().parents[1]
def outputs():
    generator=runpy.run_path(str(ROOT/'scripts/generate-grain.py'))
    packed=[]
    for suffix,density in [('-light',14),('',50),('-hard',66)]:
        for variant in range(4):
            pixels=generator['pencil'](variant,density)
            yield Path(f'resources/grain/pencil{variant}{suffix}.png'),generator['png'](pixels)
            packed.append(bytes(sum((1 << (7-bit)) if pixels[offset+bit]<128 else 0 for bit in range(8)) for offset in range(0,len(pixels),8)))
    header='/* Copyright 2026 ALTESSA SOLUTIONS INC.\n * Use of this source code is governed by an MIT-style license that can be\n * found in the LICENSE file. */\n\n/* Generated by scripts/embed-pencil.py from our procedural pencil tiles.\n * 64x64, MSB first, row zero at top; 1 means ink. Do not edit. */\n'
    header+='static const uint8_t pencil_tiles[12][512] = {\n'
    for tile in packed:
        header+='    {\n'
        for offset in range(0,len(tile),16):header+='        '+', '.join(f'0x{v:02x}' for v in tile[offset:offset+16])+',\n'
        header+='    },\n'
    header+='};\n'
    yield Path('src/rmr_pencil_tiles.h'),header.encode()
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--swift',type=Path)
    args=parser.parse_args()
    for name,data in outputs():
        path=ROOT/name
        if args.check:
            if not path.is_file() or path.read_bytes()!=data:parser.exit(1,f'Changed generated file: {name}\n')
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
        if args.swift and name.suffix=='.png':
            other=args.swift/'Sources/RMRender/Grain'/name.name
            if other.read_bytes()!=data:parser.exit(1,f'Swift asset differs: {other}\n')
    print('Twelve own pencil tiles and embedded bytes verified' if args.check else 'Twelve own pencil tiles and embedded bytes generated')
if __name__=='__main__':main()
