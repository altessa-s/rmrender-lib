// Prints backends/apple/rmr_alphabetic.h from the Unicode scalar properties of
// the Swift standard library: swift scripts/generate-unicode.swift > <file>.
// The output is data only; building RMRender does not require Swift.
func emit(_ name: String, _ matches: (Unicode.Scalar) -> Bool) {
    print("static bool \(name)(uint32_t c) {\nstatic const uint32_t ranges[][2] = {")
    var first: UInt32?, last: UInt32 = 0
    for value: UInt32 in 0...0x10ffff {
        if let scalar = Unicode.Scalar(value), matches(scalar) {
            if first == nil { first = value }
            last = value
        } else if let start = first {
            print("{\(start),\(last)},")
            first = nil
        }
    }
    if let first { print("{\(first),\(last)},") }
    print("""
    };
    size_t lo=0,hi=sizeof ranges/sizeof ranges[0];
    while(lo<hi) {
        size_t mid=lo+(hi-lo)/2;
        if(c<ranges[mid][0]) hi=mid;
        else if(c>ranges[mid][1]) lo=mid+1;
        else return true;
    }
    return false;
    }
    """)
}
print("""
/* Copyright 2026 ALTESSA SOLUTIONS INC.
 * Use of this source code is governed by an MIT-style license that can be
 * found in the LICENSE file. */

/* Generated by scripts/generate-unicode.swift; Unicode scalar properties. */
""")
print("#include <stddef.h>\n#include <stdint.h>")
emit("alphabetic") { $0.properties.isAlphabetic }
emit("nonspacing") { $0.properties.generalCategory == .nonspacingMark }
